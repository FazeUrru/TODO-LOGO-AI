/**
 * Catálogo de modelos 3D «ya hechos» de todólogo.ai.
 *
 * Cada modelo es una receta: una lista de primitivas (caja, esfera, cilindro,
 * cono, toro) con posición, tamaño, color y rotación. El visor WebGL las
 * construye al vuelo, así que 125 modelos pesan menos que una sola foto.
 *
 * Sistema de coordenadas compartido: el suelo está en y=0, el modelo centrado
 * en x/z y con altura total aproximada de 1,5 a 3 unidades.
 */

export type Part3D = [
  shape: "bx" | "sp" | "cy" | "co" | "to",
  x: number, y: number, z: number,
  a: number, b: number, c: number,
  color: string,
  rx: number, ry: number, rz: number
];

export interface Recipe3D {
  id: string;
  name: string;
  cat: string;
  kw: string[]; // palabras clave para la detección en el prompt
  parts: Part3D[];
}

