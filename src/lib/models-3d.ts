/** Categorías de la galería (los 8 clásicos entran en «Clásicos»). */
export const MODEL_3D_CATS = [
  "Clásicos", "Animales", "Vehículos", "Lugares", "Espacio", "Muebles",
  "Comida", "Deporte", "Música", "Personajes", "Naturaleza", "Objetos",
  "Herramientas", "Fiestas", "Ciencia", "Aventura",
] as const;

/** Todos los ids disponibles: 8 clásicos + 125 recetas = 133 modelos. */
export const PRESET_3D_IDS = ["cohete", "robot", "casa", "coche", "planeta", "arbol", "ciudad", "terreno"] as const;

export const ALL_3D_IDS: string[] = [...PRESET_3D_IDS, ...RECIPES_3D.map((r) => r.id)];

export function recipeById(id: string): Recipe3D | undefined {
  return RECIPES_3D.find((r) => r.id === id);
}

function normalize(s: string): string {
  return s
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "");
}

/**
 * Detecta el modelo 3D que pide el usuario a partir del texto:
 * primero los 8 clásicos (por pistas fuertes) y después las 125 recetas
 * por nombre y palabras clave (con plural y sin acentos).
 */
export function detectModel3D(prompt: string): string {
  const p = normalize(prompt);
  const strong: [RegExp, string][] = [
    [/cohete|rocket|espacial|nave\b/, "cohete"],
    [/robot|androide|mech|automata/, "robot"],
    [/casa\b|hogar|bungalow|chalet/, "casa"],
    [/coche|carro\b|vehiculo|formula/, "coche"],
    [/planeta|sistema solar|orbita/, "planeta"],
    [/arbol\b|bosque/, "arbol"],
    [/ciudad|rascacielos|urbe/, "ciudad"],
    [/terreno|paisaje|montanas|colinas/, "terreno"],
  ];
  for (const [re, id] of strong) if (re.test(p)) return id;

  let best: { id: string; len: number } | null = null;
  for (const r of RECIPES_3D) {
    const names = [r.id, ...r.kw];
    for (const raw of names) {
      const n = normalize(raw);
      for (const cand of [n, `${n}s`, `${n}es`]) {
        if (cand.length >= 3 && p.includes(cand) && (!best || cand.length > best.len)) {
          best = { id: r.id, len: cand.length };
        }
      }
    }
  }
  if (best) return best.id;
  return PRESET_3D_IDS[Math.floor(Math.random() * PRESET_3D_IDS.length)];
}


